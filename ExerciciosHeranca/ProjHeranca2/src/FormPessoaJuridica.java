    private void BotaoCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotaoCadastrarActionPerformed
        // TODO add your handling code here:
        juridica.endereco=this.TextoEndreco.getText();
        juridica.estado=this.TextoEstado.getText();
        juridica.cidade=this.TextoCidade.getText();
        juridica.cnpj=Integer.parseInt(this.TextoCNPJ.getText());
        juridica.NomeFantasia=this.TextoNomeFantasia.getText();
        //Deletando os campos
        this.TextoEndreco.setText((""));
        this.TextoCidade.setText((""));
        this.TextoEstado.setText((""));
        this.TextoCNPJ.setText((""));
        this.TextoNomeFantasia.setText((""));
        
    }//GEN-LAST:event_BotaoCadastrarActionPerformed

